#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
zhpatch —— Unity 游戏文本抽取 / 批量翻译 / XUnity 翻译表生成

依赖: pip install UnityPy
用法:
  python zhpatch.py extract   <游戏根目录或 *_Data 目录>  -o strings.json
  python zhpatch.py translate strings.json -o results.json [--provider deepseek] [--key ...] [--workers 4]
  python zhpatch.py build     results.json -o _AutoGeneratedTranslations.txt
  python zhpatch.py stats     strings.json

产物 _AutoGeneratedTranslations.txt 放到:
  <游戏目录>/BepInEx/Translation/zh-CN/Text/
"""
import argparse
import json
import os
import re
import sys
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor

KANA = re.compile(r"[\u3040-\u309f\u30a0-\u30ff\u30fc]")
CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")

LEAD_MARK = re.compile(r"^[;:#*\-+>\s]+")
KEYVAL = re.compile(r"^[A-Za-z0-9_\-]+:\s*(.+)$")


def variants(line):
    """一行脚本可能对应多个渲染文本形态，全部纳入池子。"""
    out = [line]
    stripped = LEAD_MARK.sub("", line).strip()
    if stripped and stripped != line:
        out.append(stripped)
    for cand in list(out):
        m = KEYVAL.match(cand)
        if m:
            out.append(m.group(1).strip())
    return out


SKIP_PREFIX = ("@", "#", "//", "<", "{", "m_", "0x")


# ---------------------------------------------------------------- extract
def find_assets(game_dir):
    """找出所有含文本的 assets 文件。"""
    game_dir = os.path.abspath(game_dir)
    if not os.path.isdir(game_dir):
        raise SystemExit("目录不存在: " + game_dir)

    roots = []
    if game_dir.lower().endswith("_data") or os.path.basename(game_dir).lower().endswith("_data"):
        roots = [game_dir]
    else:
        for name in os.listdir(game_dir):
            if name.lower().endswith("_data") and os.path.isdir(os.path.join(game_dir, name)):
                roots.append(os.path.join(game_dir, name))
        if not roots:
            raise SystemExit("没找到 *_Data 目录，请把参数指向游戏根目录")

    files = []
    for root in roots:
        for dirpath, _dirs, names in os.walk(root):
            for n in names:
                if n.endswith(".assets") or n.endswith(".bundle") or n.endswith(".unity3d"):
                    files.append(os.path.join(dirpath, n))
    # 优先 resources.assets / sharedassets / level*
    files.sort(key=lambda p: (0 if "resources.assets" in p else 1 if "sharedassets" in p else 2, p))
    return files


def decode_textasset(raw):
    if isinstance(raw, str):
        return raw
    for enc in ("utf-8-sig", "utf-8", "utf-16-le", "utf-16", "gb18030", "cp932"):
        try:
            t = raw.decode(enc)
            if KANA.search(t):
                return t
        except Exception:
            continue
    return raw.decode("utf-8", "replace")


def walk_strings(obj, out, depth=0):
    """递归收集 MonoBehaviour 里的字符串（typetree 可读时）。"""
    if depth > 6:
        return
    if isinstance(obj, str):
        out.add(obj)
    elif isinstance(obj, dict):
        for v in obj.values():
            walk_strings(v, out, depth + 1)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            walk_strings(v, out, depth + 1)


def extract(game_dir, out_path, min_len=2, keep_ascii=False):
    import UnityPy

    files = find_assets(game_dir)
    print(f"扫描 {len(files)} 个资源文件 …", flush=True)
    pool = set()
    per_file = []

    for fp in files:
        try:
            env = UnityPy.load(fp)
        except Exception as e:
            print(f"  跳过 {os.path.basename(fp)}: {type(e).__name__}", flush=True)
            continue
        found = 0
        for o in env.objects:
            tname = o.type.name
            try:
                if tname == "TextAsset":
                    data = o.read()
                    txt = decode_textasset(getattr(data, "m_Script", b""))
                    # 整篇 + 段落（对话通常按空行分段，XUnity 匹配的是渲染出的整段）
                    chunks = [txt] + [b for b in re.split(r"\n\s*\n", txt) if b.strip()]
                elif tname == "MonoBehaviour":
                    try:
                        tree = o.read_typetree()
                    except Exception:
                        continue
                    strs = set()
                    walk_strings(tree, strs)
                    chunks = [s for s in strs if len(s) >= min_len]
                else:
                    continue
            except Exception:
                continue

            for chunk in chunks:
                whole = chunk.strip()
                if "\n" in whole and KANA.search(whole) and len(whole) < 4000 and whole not in pool:
                    pool.add(whole)
                    found += 1
                for line in chunk.splitlines():
                    line = line.strip()
                    if len(line) < min_len:
                        continue
                    if line.startswith(SKIP_PREFIX):
                        continue
                    if CTRL.search(line):
                        continue
                    if not KANA.search(line) and not keep_ascii:
                        continue
                    for cand in variants(line):
                        if len(cand) < min_len or cand in pool:
                            continue
                        if not KANA.search(cand) and not keep_ascii:
                            continue
                        pool.add(cand)
                        found += 1
        if found:
            per_file.append((os.path.basename(fp), found))

    strings = sorted(pool)
    json.dump({"count": len(strings), "strings": strings},
              open(out_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\n各文件贡献:")
    for n, c in per_file[:15]:
        print(f"  {n}: {c}")
    print(f"\n共抽取 {len(strings)} 条 → {out_path}")
    if len(strings) == 0:
        print("警告: 一条都没抓到。可能文本不在 TextAsset 里（如 Dialogue System 的数据库），"
              "或 typetree 被 IL2CPP 剥离。此时改用 XUnity 运行时抓取（见 SKILL.md）。")
    return len(strings)


# ---------------------------------------------------------------- translate
PROVIDERS = {
    "deepseek": ("https://api.deepseek.com/chat/completions", "deepseek-chat", "DEEPSEEK_API_KEY"),
    "zhipu": ("https://open.bigmodel.cn/api/paas/v4/chat/completions", "glm-4-flash", "ZHIPU_API_KEY"),
    "moonshot": ("https://api.moonshot.cn/v1/chat/completions", "moonshot-v1-8k", "MOONSHOT_API_KEY"),
}

SYS_BASE = (
    "你是专业的游戏本地化译者。用户给你一个 JSON 数组，每项是一句待译文本（多为日文）。\n"
    "严格输出 JSON 数组，元素个数与顺序必须与输入一致，不要代码块，不要解释。\n"
    "规则:\n"
    "1) 含假名的条目必须译成简体中文，禁止原样返回日文；\n"
    "2) 纯英文/纯数字/纯符号原样返回；\n"
    "3) 保留「」『』、……、♥♪、――、换行等符号与标点风格；\n"
    "4) 人名/专有名词按术语表固定译法，术语表没有的保持音译一致；\n"
    "5) 台词口语化，旁白书面化。"
)


def load_key(provider, cli_key, env_file):
    if cli_key:
        return cli_key
    _p, _m, envname = PROVIDERS[provider]
    if os.environ.get(envname):
        return os.environ[envname].strip()
    for path in (env_file, os.path.join(os.getcwd(), ".env")):
        if path and os.path.exists(path):
            for line in open(path, encoding="utf-8", errors="replace"):
                if line.strip().startswith(envname + "="):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    raise SystemExit(f"缺少 {envname}，用 --key 传入或写进 .env")


def load_glossary(path):
    lines = []
    if path and os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                lines.append(line)
    return lines


def ask(url, model, key, texts, glossary, tries=4):
    sys_msg = SYS_BASE
    if glossary:
        sys_msg += "\n\n术语表（左=右）:\n" + "\n".join(glossary[:300])
    body = json.dumps({
        "model": model,
        "messages": [
            {"role": "system", "content": sys_msg},
            {"role": "user", "content": json.dumps(texts, ensure_ascii=False)},
        ],
        "temperature": 0.3,
        "max_tokens": 8000,
    }).encode("utf-8")

    last = ""
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, data=body, headers={
                "Content-Type": "application/json",
                "Authorization": "Bearer " + key,
            })
            with urllib.request.urlopen(req, timeout=240) as r:
                res = json.loads(r.read().decode("utf-8"))
            txt = res["choices"][0]["message"]["content"].strip()
            txt = re.sub(r"^```(?:json)?|```$", "", txt, flags=re.M).strip()
            arr = json.loads(txt)
            if isinstance(arr, list) and len(arr) == len(texts):
                return arr
            last = f"返回长度不符 {len(arr) if isinstance(arr, list) else '?'} != {len(texts)}"
        except Exception as e:
            last = f"{type(e).__name__}: {str(e)[:120]}"
        time.sleep(2 + 3 * attempt)
    raise RuntimeError(last)


def translate(strings_path, out_path, provider, key, model, base_url, batch, workers, glossary_path, retries):
    data = json.load(open(strings_path, encoding="utf-8"))
    strings = data["strings"] if isinstance(data, dict) else data
    url = base_url or PROVIDERS[provider][0]
    model = model or PROVIDERS[provider][1]
    glossary = load_glossary(glossary_path)

    done = {}
    if os.path.exists(out_path):
        for line in open(out_path, encoding="utf-8"):
            try:
                d = json.loads(line)
                for i, z in zip(d["idx"], d["zh"]):
                    done[str(i)] = z
            except Exception:
                pass
    todo = [i for i in range(len(strings)) if str(i) not in done]
    batches = [todo[k:k + batch] for k in range(0, len(todo), batch)]
    print(f"共 {len(strings)} 条，已译 {len(done)}，待译 {len(todo)}（{len(batches)} 批，并发 {workers}）", flush=True)

    lock_out = out_path

    def work(idx):
        texts = [strings[i] for i in idx]
        for _ in range(retries):
            try:
                arr = ask(url, model, key, texts, glossary)
                with open(lock_out, "a", encoding="utf-8") as f:
                    f.write(json.dumps({"idx": idx, "zh": arr}, ensure_ascii=False) + "\n")
                return True
            except Exception as e:
                print(f"  批次 {idx[0]} 失败: {e}", flush=True)
        return False

    ok = 0
    with ThreadPoolExecutor(max_workers=workers) as ex:
        for n, res in enumerate(ex.map(work, batches), 1):
            ok += bool(res)
            if n % 10 == 0 or n == len(batches):
                print(f"进度 {n}/{len(batches)} 批，成功 {ok}", flush=True)

    left = len(strings) - len(done) - sum(len(strings[i:i + 1]) for i in [])
    print(f"完成: 成功批次 {ok}/{len(batches)}。可重复执行本命令续跑（已译部分不会重译）。")


# ---------------------------------------------------------------- build
def build(results_path, out_path, strings_path=None):
    entries = {}
    order = []
    for line in open(results_path, encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        try:
            d = json.loads(line)
        except Exception:
            continue
        for i, z in zip(d["idx"], d["zh"]):
            z = (z or "").strip()
            if not z:
                continue
            entries[str(i)] = z
            if str(i) not in order:
                order.append(str(i))

    strings = None
    if strings_path:
        data = json.load(open(strings_path, encoding="utf-8"))
        strings = data["strings"] if isinstance(data, dict) else data

    def esc(s):
        return s.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "")

    lines, seen = [], set()
    for i in order:
        if strings is None:
            continue
        src = strings[int(i)]
        if src in seen:
            continue
        if src.strip() == entries[i].strip():
            continue
        seen.add(src)
        lines.append(f"{esc(src)}={esc(entries[i])}")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"写出 {len(lines)} 条 → {out_path}")
    print("放到: <游戏目录>/BepInEx/Translation/zh-CN/Text/_AutoGeneratedTranslations.txt")


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description="Unity 游戏文本抽取/翻译/XUnity 表生成")
    sub = ap.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("extract", help="从游戏资源里抽取日文文本")
    e.add_argument("game_dir")
    e.add_argument("-o", "--out", default="strings.json")
    e.add_argument("--min-len", type=int, default=2)
    e.add_argument("--keep-ascii", action="store_true", help="保留不含假名的行（英文游戏用）")

    t = sub.add_parser("translate", help="批量翻译 strings.json")
    t.add_argument("strings")
    t.add_argument("-o", "--out", default="results.jsonl")
    t.add_argument("--provider", default="deepseek", choices=list(PROVIDERS))
    t.add_argument("--key", default=None)
    t.add_argument("--model", default=None)
    t.add_argument("--base-url", default=None)
    t.add_argument("--batch", type=int, default=8)
    t.add_argument("--workers", type=int, default=4)
    t.add_argument("--glossary", default="glossary.txt")
    t.add_argument("--retries", type=int, default=3)
    t.add_argument("--env-file", default=".env")

    b = sub.add_parser("build", help="生成 _AutoGeneratedTranslations.txt")
    b.add_argument("results")
    b.add_argument("-o", "--out", default="_AutoGeneratedTranslations.txt")
    b.add_argument("-s", "--strings", default="strings.json")

    s = sub.add_parser("stats", help="看看抽出来多少条")
    s.add_argument("strings")

    a = ap.parse_args()
    if a.cmd == "extract":
        extract(a.game_dir, a.out, a.min_len, a.keep_ascii)
    elif a.cmd == "translate":
        key = load_key(a.provider, a.key, a.env_file)
        translate(a.strings, a.out, a.provider, key, a.model, a.base_url,
                  a.batch, a.workers, a.glossary, a.retries)
    elif a.cmd == "build":
        build(a.results, a.out, a.strings)
    elif a.cmd == "stats":
        data = json.load(open(a.strings, encoding="utf-8"))
        arr = data["strings"] if isinstance(data, dict) else data
        print(f"{len(arr)} 条，平均 {sum(len(x) for x in arr)/max(1,len(arr)):.1f} 字")
        for x in arr[:5]:
            print("  ", x[:70])


if __name__ == "__main__":
    main()
